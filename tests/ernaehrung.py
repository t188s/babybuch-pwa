import asyncio, sys, http.server, threading, functools, os
from playwright.async_api import async_playwright
WEB, AUS = sys.argv[1], sys.argv[2]; os.makedirs(AUS, exist_ok=True)
http.server.SimpleHTTPRequestHandler.log_message = lambda *a: None
srv = http.server.ThreadingHTTPServer(("127.0.0.1", 8775), functools.partial(http.server.SimpleHTTPRequestHandler, directory=WEB))
threading.Thread(target=srv.serve_forever, daemon=True).start()
async def main():
    async with async_playwright() as pw:
        b = await pw.chromium.launch(executable_path="/usr/bin/google-chrome", args=["--no-sandbox"])
        ctx = await b.new_context(viewport={"width": 375, "height": 667}, device_scale_factor=2, is_mobile=True, has_touch=True, locale="de-DE")
        p = await ctx.new_page(); fehler = []
        p.on("pageerror", lambda e: fehler.append(str(e)))
        p.on("console", lambda m: fehler.append(m.text) if m.type == "error" else None)
        await p.goto("http://127.0.0.1:8775/"); await p.wait_for_timeout(1200)
        await p.locator("dialog[open]").last.get_by_role("button", name="Beispielkind ansehen").click()
        await p.wait_for_function("!document.querySelector('dialog[open]')", timeout=30000)
        await p.reload(); await p.wait_for_timeout(1800)
        wahl = await p.evaluate("[...document.querySelectorAll('#pwa-ern-wahl button')].map(b => b.innerText + (b.classList.contains('aktiv') ? '*' : ''))")
        print("Wahl:", wahl, "· Stillen scrollt:", await p.evaluate("document.getElementById('scroll').scrollHeight > document.getElementById('scroll').clientHeight + 2"))
        await p.screenshot(path=f"{AUS}/1_brust.png")
        await p.click("#pwa-ern-wahl button[data-w='flasche']"); await p.wait_for_timeout(500)
        print("Fläschchen-Status:", (await p.inner_text("#pwa-ern-status")).replace("\n", " | "))
        await p.click("#pwa-ern .formular button[data-w='pre']")
        await p.evaluate("(() => { const r = document.querySelector('#pwa-ern input[type=range]'); r.value = 120; r.dispatchEvent(new Event('input')); })()")
        print("Zusammenfassung:", (await p.inner_text("#pwa-ern .zusammenfassung")).replace("\n", " | "))
        await p.screenshot(path=f"{AUS}/2_flasche.png")
        await p.click("#pwa-ern-speichern"); await p.wait_for_timeout(700)
        print("Toast:", await p.inner_text("#toast-text"), "· Status:", (await p.inner_text("#pwa-ern-status")).replace("\n", " | "))
        print("Stillen scrollt (Fläschchen):", await p.evaluate("document.getElementById('scroll').scrollHeight > document.getElementById('scroll').clientHeight + 2"))
        await p.click("#pwa-ern-wahl button[data-w='abpumpen']"); await p.wait_for_timeout(500)
        await p.screenshot(path=f"{AUS}/3_pumpen.png")
        await p.click("#pwa-ern-speichern"); await p.wait_for_timeout(600)
        # Beikost einschalten
        await p.evaluate("einstellungenOeffnen()"); await p.wait_for_timeout(500)
        await p.locator("#pwa-ern-einst input[value='beikost']").check(); await p.wait_for_timeout(600)
        await p.locator("#pwa-ern-einst").scroll_into_view_if_needed(); await p.screenshot(path=f"{AUS}/4_einstellung.png")
        await p.keyboard.press("Escape"); await p.wait_for_timeout(300)
        await p.click("#pwa-ern-wahl button[data-w='beikost']"); await p.wait_for_timeout(500)
        print("Beikost speichern gesperrt ohne Was:", await p.is_disabled("#pwa-ern-speichern"))
        await p.fill("#pwa-bk-was", "Karotte"); await p.click("#pwa-ern .pwa-bk-neu .schalter")
        await p.screenshot(path=f"{AUS}/5_beikost.png")
        await p.click("#pwa-ern-speichern"); await p.wait_for_timeout(600)
        print("Beikost-Status:", (await p.inner_text("#pwa-ern-status")).replace("\n", " | "))
        # Letzte Einträge → Ändern
        await p.click("#pwa-ern-wahl button[data-w='flasche']"); await p.wait_for_timeout(500)
        await p.click("#pwa-ern-status .status-knopf"); await p.wait_for_timeout(500)
        await p.locator("dialog[open] li").first.get_by_role("button", name="Ändern").click(); await p.wait_for_timeout(300)
        await p.locator("dialog[open]").last.locator("input[type=number]").fill("130")
        await p.locator("dialog[open]").last.get_by_role("button", name="Speichern").click(); await p.wait_for_timeout(700)
        print("nach Ändern:", (await p.inner_text("#pwa-ern-status")).replace("\n", " | "))
        # Auswertung
        await p.click("#tab-auswertung"); await p.wait_for_timeout(1200)
        print("Kacheln:", await p.evaluate("[...document.querySelectorAll('#kacheln .kachel .titel')].map(t => t.innerText)"),
              "· Unterreiter sichtbar:", await p.evaluate("!document.getElementById('pwa-aw-ern-knopf').hidden"))
        await p.locator("#kacheln .pwa-kachel").first.scroll_into_view_if_needed(); await p.screenshot(path=f"{AUS}/6_ueberblick.png")
        await p.click("#pwa-aw-ern-knopf"); await p.wait_for_timeout(900)
        print("Teil 24h:", (await p.inner_text("#pwa-aw-ern"))[:260].replace("\n", " | "))
        await p.screenshot(path=f"{AUS}/7_teil24h.png")
        await p.evaluate("(() => { const r = document.getElementById('aw-regler'); r.value = 4; r.dispatchEvent(new Event('input')); r.dispatchEvent(new Event('change')); })()")
        await p.wait_for_timeout(1200)
        print("Teil 14T:", (await p.inner_text("#zeitraum-titel")), "·", (await p.inner_text("#pwa-aw-ern"))[:200].replace("\n", " | "))
        await p.screenshot(path=f"{AUS}/8_teil14.png", full_page=False)
        # Nur Fläschchen
        await p.click("#tab-eintragen"); await p.wait_for_timeout(400)
        await p.evaluate("einstellungenOeffnen()"); await p.wait_for_timeout(400)
        for a in ("stillen", "abpumpen", "beikost"): await p.locator(f"#pwa-ern-einst input[value='{a}']").uncheck(); await p.wait_for_timeout(400)
        await p.keyboard.press("Escape"); await p.wait_for_timeout(400)
        print("Nur Fläschchen – Reiter:", await p.inner_text('.alltag-wahl button[data-a="eintragen"]'), "· Wahl sichtbar:", await p.evaluate("!document.getElementById('pwa-ern-wahl').hidden"),
              "· Modus:", await p.evaluate("document.getElementById('bereich-eintragen').dataset.pwaModus"), "· Titel:", await p.inner_text("#kopf-titel"))
        await p.screenshot(path=f"{AUS}/9_nur_flasche.png")
        print("Fehler:", fehler or "keine"); await b.close()
asyncio.run(main())
